let currentLang = 'en';

function detectLang() {
    try {
        const saved = localStorage.getItem(LANG_KEY);
        if (saved && SUPPORTED_LANGS.includes(saved)) return saved;
    } catch (_) {}
    const nav = (navigator.language || 'en').slice(0, 2).toLowerCase();
    if (SUPPORTED_LANGS.includes(nav)) return nav;
    return 'en';
}

function t(key, vars) {
    const pack = UI_I18N[currentLang] || UI_I18N.en;
    let s = pack[key] ?? UI_I18N.en[key] ?? key;
    if (vars) {
        Object.entries(vars).forEach(([k, v]) => {
            s = s.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
        });
    }
    return s;
}

function tItem(enName) {
    if (!enName) return '';
    if (currentLang === 'en') return enName;
    const map = (typeof ITEM_I18N !== 'undefined' && ITEM_I18N[currentLang]) || {};
    return map[enName] || enName;
}

function tCat(enCat) {
    const key = CAT_I18N_KEY[enCat];
    return key ? t(key) : enCat;
}

/** Поиск: совпадение по EN-ключу или локализованному имени */
function itemMatchesSearch(enName, term) {
    if (!term) return true;
    const q = term.toLowerCase();
    if (enName.toLowerCase().includes(q)) return true;
    if (tItem(enName).toLowerCase().includes(q)) return true;
    return false;
}

function setLanguage(lang, opts = {}) {
    if (!SUPPORTED_LANGS.includes(lang)) lang = 'en';
    currentLang = lang;
    try { localStorage.setItem(LANG_KEY, lang); } catch (_) {}
    document.documentElement.lang = lang;
    applyStaticI18n();
    const sel = document.getElementById('lang-select');
    if (sel) sel.value = lang;
    if (opts.rerender !== false && typeof window.__i18nRerender === 'function') {
        window.__i18nRerender();
    }
    if (window.ArcTour) window.ArcTour.refresh();
}

function applyStaticI18n() {
    document.title = t('pageTitle');
    document.documentElement.style.setProperty('--kofi-label', `"${t('supportDev')}"`);
    document.querySelectorAll('[data-i18n]').forEach(node => {
        const key = node.getAttribute('data-i18n');
        if (!key) return;
        const val = t(key);
        if (node.tagName === 'INPUT' || node.tagName === 'TEXTAREA') {
            // not text content
        } else {
            node.textContent = val;
        }
    });
    document.querySelectorAll('[data-i18n-html]').forEach(node => {
        const key = node.getAttribute('data-i18n-html');
        if (key) node.innerHTML = t(key);
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(node => {
        const key = node.getAttribute('data-i18n-placeholder');
        if (key) node.setAttribute('placeholder', t(key));
    });
    document.querySelectorAll('[data-i18n-title]').forEach(node => {
        const key = node.getAttribute('data-i18n-title');
        if (key) node.setAttribute('title', t(key));
    });
    document.querySelectorAll('[data-i18n-aria]').forEach(node => {
        const key = node.getAttribute('data-i18n-aria');
        if (key) node.setAttribute('aria-label', t(key));
    });
    // accordion titles with toggle icon
    const ing = document.querySelector('[data-i18n-acc="ingredients"]');
    if (ing) {
        const icon = ing.querySelector('.toggle-icon');
        const ic = icon ? icon.textContent : '▶';
        ing.innerHTML = `${t('ingredients')} <span class="toggle-icon">${ic}</span>`;
    }
    const rec = document.querySelector('[data-i18n-acc="recipeBreakdown"]');
    if (rec) {
        const icon = rec.querySelector('.toggle-icon');
        const ic = icon ? icon.textContent : '▶';
        rec.innerHTML = `${t('recipeBreakdown')} <span class="toggle-icon">${ic}</span>`;
    }
}

